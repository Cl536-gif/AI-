    够了，不要把第一次问它时说过的认可、纠正说明等一次性内容（比如
    第7条的局部减脂纠正、第19条的首次认可）重新完整说一遍——那些
    内容只在第一次触发时说一次，重复说等于把整个开场白复读了一遍，
    会显得很奇怪。

【校园场景真实感铁律】
